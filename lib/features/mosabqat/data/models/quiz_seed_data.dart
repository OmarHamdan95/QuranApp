/// Get questions filtered by category and difficulty.
List<QuizQuestion> getQuestionsByCategory(
  QuizCategory category,
  QuizDifficulty difficulty,
  int count,
) {
  var filtered = kSeedQuestions
      .where((q) => q.category == category && q.difficulty == difficulty)
      .toList();

  if (filtered.length < count) {
    // Fall back to any difficulty in this category
    filtered = kSeedQuestions
        .where((q) => q.category == category)
        .toList();
  }

  filtered.shuffle();
  return filtered.take(count).toList();
}

/// Get mixed questions for daily challenge.
List<QuizQuestion> getDailyChallengeQuestions(int count) {
  final all = List<QuizQuestion>.from(kSeedQuestions);
  all.shuffle();
  return all.take(count).toList();
}
